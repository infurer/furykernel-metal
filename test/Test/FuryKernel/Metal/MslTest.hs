{- | C = A · Bᵀ in 8×8 fragments, A and B 16 rows of k, B's tiles staged in
threadgroup memory and loaded from there transposed, as in furykernel's
tests.
-}
staged :: Kernel AppleGPU9
staged = kernel "staged" $ do
  k <- dim "k" (DimRange 8 256 8)
  a <- buffer @ReadOnly @16 @BF16 "a" (16 * k)
  b <- buffer @ReadOnly @16 @BF16 "b" (16 * k)
  c <- buffer @WriteOnly @16 @Float "c" 256
  threads @128
  groups 1
  pure $ do
    tile <- tgArray @128 @BF16 "tile"
    pure $ do
      row0 <- let_ "row0" ((simdGroupIndex `quotE` 2) * 8)
      col0 <- let_ "col0" ((simdGroupIndex `remE` 2) * 8)
      acc <- fragment @Float "acc"
      fa <- fragment @BF16 "fa"
      fb <- fragment @BF16 "fb"
      forU "p" 0 (k `quotE` 8) $ \p -> do
        tgStore tile threadIndex (load b ((threadIndex `quotE` 8) * k + p * 8 + threadIndex `remE` 8))
        barrier
        fragLoad fa a (row0 * k + p * 8) k
        fragLoadTgT fb tile (col0 * 8) 8
        fragMma acc fa fb acc
        barrier
      fragStore c (row0 * 16 + col0) 16 acc

-- | RMSNorm over rows of @hidden@ elements, as in furykernel's tests.
rmsnorm :: Word32 -> Kernel AppleGPU9
rmsnorm hidden = kernel "rmsnorm" $ do
  rows <- dim "rows" (DimRange 1 4096 1)
  eps <- param @Float "eps"
  x <- buffer @ReadOnly @16 @BF16 "x" (rows * h)
  w <- buffer @ReadOnly @16 @BF16 "w" h
  y <- buffer @WriteOnly @16 @BF16 "y" (rows * h)
  threads @256
  groups rows
  pure $ do
    scratch <- tgArray @8 @Float "scratch"
    pure $ do
      base <- let_ "base" (groupIndex * h)
      acc <- var "acc" 0
      strided "i" h $ \i -> do
        v <- let_ "v" (widen @Float (load x (base + i)))
        acc .= get acc + v * v
      total <- tgReduceSum "sum_sq" scratch (get acc)
      scale <- let_ "scale" (rsqrtE (total / toF32 h + eps))
      strided "j" h $ \j ->
        store y (base + j) (narrow @BF16 (widen @Float (load x (base + j)) * scale * widen @Float (load w j)))
 where
  h = fromIntegral hidden

-- | Two parameters narrowed both ways, a thread an element, under conditions of And and Or.
narrowings :: Kernel AppleGPU9
narrowings = kernel "narrowings" $ do
  a <- param @Int32 "a"
  b <- param @Word32 "b"
  c <- buffer @WriteOnly @16 @Int8 "c" 32
  w <- buffer @WriteOnly @16 @Int8 "w" 32
  cu <- buffer @WriteOnly @16 @Word8 "cu" 32
  wu <- buffer @WriteOnly @16 @Word8 "wu" 32
  threads @32
  groups 1
  pure . pure $ do
    whenLane (threadIndex .< 16 .&& a .< 0) $ do
      store c threadIndex (narrowClamped @Int8 a)
      store w threadIndex (narrowWrapped @Int8 a)
    whenLane (threadIndex .< 16 .|| b .< 5) $ do
      store cu threadIndex (narrowClamped @Word8 b)
      store wu threadIndex (narrowWrapped @Word8 b)

