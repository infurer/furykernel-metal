-- | An i32's magnitude only in a load's index.
absIndex :: Kernel AppleGPU9
absIndex = kernel "abs_index" $ do
  a <- param @Int32 "a"
  x <- buffer @ReadOnly @16 @Int32 "x" 2
  y <- buffer @WriteOnly @16 @Int32 "y" 32
  threads @32
  groups 1
  pure . pure $ store y threadIndex (load x (select (abs a .> 3) 1 0))

-- | An i32's magnitude only under a conversion.
absConverted :: Kernel AppleGPU9
absConverted = kernel "abs_converted" $ do
  a <- param @Int32 "a"
  y <- buffer @WriteOnly @16 @Float "y" 32
  threads @32
  groups 1
  pure . pure $ store y threadIndex (toF32 (select (abs a .> 5) 1 2))

-- The double negation is the point: a unary's type found through another's.
{- HLINT ignore nested "Redundant negate" -}

{- | Types found through nested expressions: an i32 magnitude, select and
SIMD-group sum in i32 arithmetic, half's double negation, an fma's
quotient in half.
-}
nested :: Kernel AppleGPU9
nested = kernel "nested" $ do
  a <- param @Int32 "a"
  b <- param @Int32 "b"
  h <- buffer @ReadOnly @16 @F16 "h" 32
  g <- buffer @WriteOnly @16 @F16 "g" 64
  y <- buffer @WriteOnly @16 @Int32 "y" 128
  threads @32
  groups 1
  pure . pure $ do
    e <- let_ "e" (load h threadIndex)
    store y threadIndex (b + abs a)
    store y (threadIndex + 32) (select (a .< 0) a b * b)
    s <- simdSum "s" a
    store y (threadIndex + 64) (s * b)
    store y (threadIndex + 96) (negate (abs a) + b)
    store g threadIndex (negate (negate e))
    store g (threadIndex + 32) (fmaE e e e / e)

-- | A threadgroup array of two floats, 8 bytes, which take 16.
tgSmall :: Kernel AppleGPU9
tgSmall = kernel "tg_small" $ do
  y <- buffer @WriteOnly @16 @Float "y" 32
  threads @32
  groups 1
  pure $ do
    s <- tgArray @2 @Float "s"
    pure $ do
      whenLane (threadIndex .< 2) $ tgStore s threadIndex (toF32 threadIndex)
      barrier
      store y threadIndex (tgLoad s (threadIndex `remE` 2))

-- | A pack loaded from a buffer the kernel also writes, and stored back.
packRw :: Kernel AppleGPU9
packRw = kernel "pack_rw" $ do
  x <- buffer @ReadWrite @16 @Float "x" 128
  threads @32
  groups 1
  pure . pure $ do
    v <- loadPack @4 "v" x threadIndex
    storePack @4 x threadIndex (reverse (unpack v))
