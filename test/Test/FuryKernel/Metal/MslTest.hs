-- | The lowering of a set of kernels.
lowered :: [Kernel AppleGPU9] -> Either String Lowered
lowered ks = case traverse check ks of
  Left fs -> Left (show fs)
  Right cs -> either (Left . show) Right (backendLower metal cs)

-- | A set of kernels' translation unit, past its first four lines.
unit :: [Kernel AppleGPU9] -> Either String [T.Text]
unit ks = drop 4 . T.lines . (.loweredSource) <$> lowered ks

-- | The lines of a kernel's body, from its one translation unit.
body :: Kernel AppleGPU9 -> Either String [T.Text]
body k = case check k of
  Left fs -> Left (show fs)
  Right c -> case backendLower metal [c] of
    Left fs -> Left (show fs)
    Right l -> Right (takeWhile (/= "}") (drop 1 (dropWhile (/= "{") (dropWhile (not . T.isPrefixOf "kernel void") (T.lines l.loweredSource)))))

-- | The findings 'metal' refuses a checked kernel with, rendered.
refused :: Kernel AppleGPU9 -> Either String [T.Text]
refused k = case check k of
  Left fs -> Left (show fs)
  Right c -> case backendLower metal [c] of
    Left fs -> Right (map renderFinding fs)
    Right _ -> Left "lowered"

-- | Four elements a thread stored to threadgroup memory at once.
tgPacked :: Kernel AppleGPU9
tgPacked = kernel "tg_packed" $ do
  a <- buffer @ReadOnly @16 @Float "a" 1024
  b <- buffer @WriteOnly @16 @Float "b" 256
  threads @256
  groups 1
  pure $ do
    packed <- tgArray @1024 @Float "staged"
    plain <- tgArray @256 @Float "plain"
    pure $ do
      tgStorePack packed threadIndex [load a (threadIndex * 4 + fromIntegral e) | e <- [0 .. 3 :: Int]]
      tgStore plain threadIndex 0
      barrier
      store b threadIndex (tgLoad packed threadIndex + tgLoad plain threadIndex)

-- | y = x * s, eight elements per lane at once, as in furykernel's tests.
scalePacked :: Kernel AppleGPU9
scalePacked = kernel "scale_packed" $ do
  packs <- dim "packs" (DimRange 1 8192 1)
  s <- param @Float "s"
  x <- buffer @ReadOnly @16 @BF16 "x" (packs * 8)
  y <- buffer @WriteOnly @16 @BF16 "y" (packs * 8)
  threads @64
  groups 1
  pure . pure $
    strided "j" packs $ \j -> do
      v <- loadPack @8 "v" x j
      storePack @8 y j [narrow @BF16 (widen @Float e * s) | e <- unpack v]

